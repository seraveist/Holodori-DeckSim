import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compareAQ } from '../analysis/unit-score/compare-aq-20260909.mjs';
import { collectCatalog } from '../analysis/unit-score/compare-am-an-20260909.mjs';
const root = new URL('../', import.meta.url);
const read = p => JSON.parse(fs.readFileSync(new URL(p, root), 'utf8'));
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(new URL(p, root))).digest('hex');
export function verifyAQ() {
  const state = read('analysis/unit-score/experiments/AQ-status-observed-20260909.json');
  for (const key of ['frozenPlan', 'observation', 'screenshot', 'report', 'catalog', 'analysisSource']) assert.equal(hash(state[key]), state[`${key}SHA256`]);
  const result = compareAQ();
  assert.deepEqual(result, read(state.report));
  assert.ok(result.baselineComparisons.every(v => v.matches));
  assert.equal(result.frozenHypotheses.finite200.passive, 2.4);
  assert.equal(result.frozenHypotheses.finite200.observedPassive, 2.3);
  assert.equal(result.frozenHypotheses.finite200.pairMatches, false);
  assert.equal(result.frozenHypotheses.fractionalCount.pairMatches, true);
  assert.equal(result.joint.observed, 14.3);
  assert.ok(result.joint.compatible);
  assert.equal(result.arithmetic.visiblePowerSum, 127795);
  assert.equal(result.arithmetic.reportedPower, 127795);
  assert.equal(result.arithmetic.visibleScoreSum, 133.4);
  assert.equal(result.arithmetic.reportedScore, 133.4);
  const entries = collectCatalog(state.catalog);
  assert.equal(entries.length, 41);
  assert.equal(new Set(entries.map(o => o.sampleId)).size, 41);
  assert.equal(new Set(entries.map(o => [...o.memberIds].sort().join(','))).size, 23);
  for (const key of ['active', 'special']) assert.equal(entries.filter(o => o.rawGame.scoreBonusDetail[key] != null).length, 39);
  const aq = entries.find(o => o.sampleId === 'AQ');
  assert.deepEqual(aq.rawGame, result.observation.game);
  assert.deepEqual(aq.boardOverrides, { 'chr-06002': { rate: 0, cooldown: 0 }, 'chr-00022': { rate: 21.5, cooldown: 0 } });
  assert.equal(aq.rawGame.unitScore, null);
  assert.equal(aq.rawGame.scoreBonusDetail.outfit, null);
  assert.equal(result.summary.confirmedPowerComponents, 103);
  assert.equal(result.summary.positivePassiveJointCompatibility, 26);
  assert.equal(result.summary.activeMatches, 39);
  assert.equal(result.summary.spMatches, 39);
  assert.equal(result.interpretation.productionFormulaChanged, false);
  return { status: 'PASS', latestObserved: 'AQ', ...result.summary, AQ: { passive: 2.3, board: 12, finiteCountPrediction: 'REJECTED', fractionalAlternative: 'MATCHES_THIS_CONTROL' } };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(JSON.stringify(verifyAQ(), null, 2));
