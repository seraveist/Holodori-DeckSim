import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compareAP } from '../analysis/unit-score/compare-ap-20260909.mjs';
import { collectCatalog } from '../analysis/unit-score/compare-am-an-20260909.mjs';
const root = new URL('../', import.meta.url);
const read = p => JSON.parse(fs.readFileSync(new URL(p, root), 'utf8'));
const hash = p => crypto.createHash('sha256').update(fs.readFileSync(new URL(p, root))).digest('hex');
export function verifyAP() {
  const state = read('analysis/unit-score/experiments/AP-status-observed-20260909.json');
  for (const key of ['frozenPlan', 'observation', 'screenshot', 'report', 'catalog', 'analysisSource']) assert.equal(hash(state[key]), state[`${key}SHA256`]);
  const result = compareAP();
  assert.deepEqual(result, read(state.report));
  assert.equal(result.comparisons.length, 7);
  assert.ok(result.comparisons.every(v => v.matches));
  assert.ok(result.joint.compatible);
  assert.equal(result.joint.observed, 14.4);
  assert.ok(result.arithmetic.powerMatches && result.arithmetic.scoreMatches);
  assert.deepEqual(result.arithmetic.AOtoAP, { passive: .6, board: 2.7, joint: 3.3 });
  const entries = collectCatalog(state.catalog);
  assert.equal(entries.length, 40);
  assert.equal(new Set(entries.map(o => o.sampleId)).size, 40);
  assert.equal(new Set(entries.map(o => [...o.memberIds].sort().join(','))).size, 23);
  for (const key of ['active', 'special']) assert.equal(entries.filter(o => o.rawGame.scoreBonusDetail[key] != null).length, 38);
  const entry = entries.find(o => o.sampleId === 'AP');
  assert.deepEqual(entry.rawGame, result.observation.game);
  assert.deepEqual(entry.boardOverrides, { 'chr-06002': { rate: 0, cooldown: 0 }, 'chr-00022': { rate: 23.5, cooldown: 0 } });
  assert.equal(entry.rawGame.unitScore, null);
  assert.equal(entry.rawGame.scoreBonusDetail.outfit, null);
  assert.equal(result.observation.scoreRowPresence.outfit, false);
  assert.equal(result.summary.activeMatches, 38);
  assert.equal(result.summary.spMatches, 38);
  assert.equal(result.summary.confirmedPowerComponents, 100);
  assert.equal(result.summary.positivePassiveJointCompatibility, 25);
  assert.equal(result.summary.prospectiveJointChecks.length, 11);
  assert.equal(result.allocationEvidence.prospectivePairs, 1);
  assert.equal(result.allocationEvidence.retrospectivePairs, 20);
  assert.equal(result.allocationEvidence.combinedPairs, 21);
  assert.deepEqual(result.allocationEvidence.historicalFailures, ['W', 'AA', 'AF', 'AH']);
  assert.equal(result.allocationEvidence.generalFormulaConfirmed, false);
  assert.equal(result.interpretation.productionFormulaChanged, false);
  return { status: 'PASS', latestObserved: 'AP', ...result.summary, AP: { passive: 2.3, board: 12.1, joint: 14.4 }, allocationEvidence: result.allocationEvidence };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log(JSON.stringify(verifyAP(), null, 2));
